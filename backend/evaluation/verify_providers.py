"""Explicit live provider smoke tests on synthetic content (may incur provider charges)."""
import argparse
import asyncio
import json
import time
from pathlib import Path
from datetime import datetime, timezone
from app.ai.llm import generate_reply
from app.ai.quiz import generate_quiz
from app.core.config import get_settings
from app.schemas.quiz import GeneratedQuiz

PASSAGES = [{"citation_id": 1, "text": "Python lists are mutable sequences: items can be replaced and appended. Tuples are immutable sequences: items cannot be reassigned. Dictionaries map unique hashable keys to values. Sets store unique elements and support membership testing. A generator produces values lazily instead of constructing an entire list. An async function returns a coroutine; await suspends that coroutine while other tasks may run."}]


async def verify(provider):
    started = time.perf_counter()
    try:
        answer = await asyncio.wait_for(generate_reply("Explain why I would use a Python list instead of a tuple.", PASSAGES, preferences={"model_provider": provider}), 90)
        quiz = GeneratedQuiz.model_validate(await asyncio.wait_for(generate_quiz("Python collections and asynchronous functions", PASSAGES, provider=provider), 120))
        valid = answer.status == "answered" and bool(answer.citation_ids) and set(answer.citation_ids) <= {1} and quiz.status == "ready" and len(quiz.questions) == 5 and all(set(q.citation_ids) <= {1} for q in quiz.questions)
        return {"provider": provider, "passed": valid, "answer_status": answer.status, "quiz_status": quiz.status, "question_count": len(quiz.questions), "latency_seconds": round(time.perf_counter()-started, 2)}
    except Exception as exc:
        # Never print credentials, prompts, or raw provider exception messages.
        return {"provider": provider, "passed": False, "error_type": type(exc).__name__, "latency_seconds": round(time.perf_counter()-started, 2)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--provider', choices=['anthropic','openai','ollama'], required=True)
    parser.add_argument('--output', type=Path, default=Path('evaluation/provider_report.json'))
    args = parser.parse_args()
    settings = get_settings()
    result = asyncio.run(verify(args.provider))
    report = {"checked_at": datetime.now(timezone.utc).isoformat(), "result": result,
        "embedding_model_unchanged": settings.embedding_model_name, "collection_unchanged": settings.qdrant_collection_name,
        "limitations": "Synthetic content only; structural checks do not establish factual answer support or quiz correctness. No embeddings are regenerated by this check."}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(report, indent=2))
    raise SystemExit(0 if result['passed'] else 1)


if __name__ == '__main__':
    main()
